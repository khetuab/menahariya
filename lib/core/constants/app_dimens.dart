  /// Calculate grid cross axis count based on screen width
  static int getGridCrossAxisCount(BuildContext context) {
    double screenWidth = MediaQuery.of(context).size.width;
    if (screenWidth < screenBreakpointSmall) {
      return 1;
    } else if (screenWidth < screenBreakpointMedium) {
      return 2;
    } else if (screenWidth < screenBreakpointLarge) {
      return 3;
    } else {
      return 4;
    }
  }

  /// Get grid child aspect ratio
  static double getGridChildAspectRatio(int crossAxisCount) {
    switch (crossAxisCount) {
      case 1:
        return 1.2;
      case 2:
        return 1.0;
      case 3:
        return 0.9;
      case 4:
        return 0.8;
      default:
        return 1.0;
    }
  }

  /// Is the current screen size considered small (mobile)
  static bool isSmallScreen(BuildContext context) {
    return MediaQuery.of(context).size.width < screenBreakpointMedium;
  }

  /// Is the current screen size considered medium (tablet)
  static bool isMediumScreen(BuildContext context) {
    double width = MediaQuery.of(context).size.width;
    return width >= screenBreakpointMedium && width < screenBreakpointLarge;
  }

  /// Is the current screen size considered large (desktop)
  static bool isLargeScreen(BuildContext context) {
    return MediaQuery.of(context).size.width >= screenBreakpointLarge;
  }

  /// Get screen size category
  static ScreenSize getScreenSize(BuildContext context) {
    double width = MediaQuery.of(context).size.width;
    if (width < screenBreakpointSmall) {
      return ScreenSize.extraSmall;
    } else if (width < screenBreakpointMedium) {
      return ScreenSize.small;
    } else if (width < screenBreakpointLarge) {
      return ScreenSize.medium;
    } else if (width < screenBreakpointExtraLarge) {
      return ScreenSize.large;
    } else {
      return ScreenSize.extraLarge;
    }
  }

  /// Get scaffold padding that adapts to screen size
  static EdgeInsets getScaffoldPadding(BuildContext context) {
    ScreenSize size = getScreenSize(context);
    switch (size) {
      case ScreenSize.extraSmall:
      case ScreenSize.small:
        return const EdgeInsets.all(padding16);
      case ScreenSize.medium:
        return const EdgeInsets.all(padding24);
      case ScreenSize.large:
      case ScreenSize.extraLarge:
        return const EdgeInsets.symmetric(
          horizontal: padding32,
          vertical: padding24,
        );
    }
  }

  /// Get card elevation based on screen size
  static double getCardElevation(BuildContext context) {
    if (isSmallScreen(context)) {
      return elevation1;
    } else if (isMediumScreen(context)) {
      return elevation2;
    } else {
      return elevation3;
    }
  }

  /// Get dialog width based on screen size
  static double getDialogWidth(BuildContext context) {
    double screenWidth = MediaQuery.of(context).size.width;
    if (screenWidth < screenBreakpointMedium) {
      return screenWidth * 0.9;
    } else if (screenWidth < screenBreakpointLarge) {
      return screenWidth * 0.6;
    } else {
      return screenWidth * 0.4;
    }
  }

  /// Get bottom sheet height based on screen size
  static double getBottomSheetHeight(BuildContext context, double percentage) {
    double screenHeight = MediaQuery.of(context).size.height;
    double maxHeight = screenHeight * 0.9;
    double desiredHeight = screenHeight * percentage;
    return desiredHeight > maxHeight ? maxHeight : desiredHeight;
  }

  /// Calculate responsive value based on screen width
  static T responsiveValue<T>({
    required BuildContext context,
    required T mobile,
    T? tablet,
    T? desktop,
  }) {
    if (isLargeScreen(context) && desktop != null) {
      return desktop;
    } else if (isMediumScreen(context) && tablet != null) {
      return tablet;
    } else {
      return mobile;
    }
  }

  /// Get responsive grid delegate
  static SliverGridDelegateWithFixedCrossAxisCount getResponsiveGridDelegate(
      BuildContext context, {
        double childAspectRatio = 1.0,
        double crossAxisSpacing = gridSpacingMedium,
        double mainAxisSpacing = gridSpacingMedium,
      }) {
    int crossAxisCount = getGridCrossAxisCount(context);
    return SliverGridDelegateWithFixedCrossAxisCount(
      crossAxisCount: crossAxisCount,
      childAspectRatio: getGridChildAspectRatio(crossAxisCount),
      crossAxisSpacing: crossAxisSpacing,
      mainAxisSpacing: mainAxisSpacing,
    );
  }
}

