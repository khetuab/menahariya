// ==================== EXTENSIONS ====================

extension EdgeInsetsExtension on EdgeInsets {
  /// Scale padding by factor
  EdgeInsets scale(double factor) {
    return EdgeInsets.only(
      left: left * factor,
      top: top * factor,
      right: right * factor,
      bottom: bottom * factor,
    );
  }
}

extension RadiusExtension on Radius {
  /// Scale radius by factor
  Radius scale(double factor) => Radius.circular(5 * factor);
}

extension BorderRadiusExtension on BorderRadius {
  /// Scale border radius by factor
  BorderRadius scale(double factor) {
    return BorderRadius.only(
      topLeft: topLeft.scale(factor),
      topRight: topRight.scale(factor),
      bottomLeft: bottomLeft.scale(factor),
      bottomRight: bottomRight.scale(factor),
    );
  }
}

extension BoxConstraintsExtension on BoxConstraints {
  /// Get constrained width
  double get constrainedWidth => maxWidth.isFinite ? maxWidth : double.infinity;

  /// Get constrained height
  double get constrainedHeight => maxHeight.isFinite ? maxHeight : double.infinity;

  /// Check if constraints are tight
  bool get isTight => minWidth == maxWidth && minHeight == maxHeight;

  /// Check if constraints are loose
  bool get isLoose => minWidth == 0 && minHeight == 0;
}